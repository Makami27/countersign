import { chromium } from "playwright";
import { OwnerAuth } from "@countersign/web/ownerAuth";
import { SqliteRows } from "@countersign/adapters/sqlite";

const BASE = process.argv[2] ?? "http://localhost:8793";
const DATABASE = process.argv[3] ?? "";
if (!DATABASE) throw new Error("Usage: loginCheck.ts <base url> <database path>");
const auth = await OwnerAuth.open(new SqliteRows(DATABASE));
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const requests: string[] = [];
page.on("response", (r) => void (r.url().includes("/api/") && requests.push(`${r.request().method()} ${new URL(r.url()).pathname} ${r.status()}`)));
const problems: string[] = [];
await page.goto(`${BASE}/app`);
await page.waitForURL(`${BASE}/app/login`, { timeout: 15_000 });
const why = await page.locator("[role=status]").first().textContent().catch(() => null);
if (!why?.includes("signed out")) problems.push(`no signed-out reason on the sign-in page (${why ?? "none"})`);
await page.fill("#code", await auth.issueCode());
await page.locator("button[type=submit]").dblclick();
await page.waitForURL(`${BASE}/app`, { timeout: 15_000 }).catch(() => problems.push("did not navigate after sign-in"));
await page.waitForFunction("!document.querySelector('#app')?.textContent?.includes('Loading your agent')", null, { timeout: 30_000 }).catch(() => problems.push("still loading 30 s after sign-in"));
const sessions = requests.filter((r) => r.startsWith("POST /api/session"));
if (sessions.length !== 1) problems.push(`expected one sign-in request, saw ${sessions.length}`);
await page.reload();
await page.waitForFunction("!document.querySelector('#app')?.textContent?.includes('Loading your agent')", null, { timeout: 30_000 }).catch(() => problems.push("still loading 30 s after reload"));
console.log(`heading after reload: ${(await page.locator("#app h1, #app h2").first().textContent())?.trim() ?? "none"}`);
console.log(requests.join("\n"));
await browser.close();
console.log(problems.length ? `PROBLEMS: ${problems.join("; ")}` : "login check passed");
process.exit(problems.length ? 1 : 0);
